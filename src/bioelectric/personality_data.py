from __future__ import annotations

import numpy as np


def encode_text(text: str) -> np.ndarray:
    """把中文语句编码为「字符 + 相邻双字」的 n-gram 计数向量。

    用字符 n-gram 而非关键词表，使未见过的新词（成语/近义词）能通过
    共享的字符关联到训练数据，获得跨词汇的泛化能力。
    """
    chars = list(text)
    unigrams = [c for c in chars]
    bigrams = [text[i:i+2] for i in range(len(text) - 1)]
    grams = unigrams + bigrams
    counts = {}
    for g in grams:
        counts[g] = counts.get(g, 0) + 1
    return counts


def build_feature_matrix(texts):
    """从文本列表构建统一的 n-gram 特征矩阵（词表来自全体数据）。"""
    all_grams = set()
    for t in texts:
        all_grams.update(encode_text(t).keys())
    vocab = {g: i for i, g in enumerate(sorted(all_grams))}
    X = np.zeros((len(texts), len(vocab)), dtype=float)
    for i, t in enumerate(texts):
        for g, c in encode_text(t).items():
            if g in vocab:
                X[i, vocab[g]] = c
    return X, vocab


