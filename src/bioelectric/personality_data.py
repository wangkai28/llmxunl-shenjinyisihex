# 关键词表：覆盖情绪四象限的中文关键词（用于 BOW 特征化）
KEYWORDS = [
    # 愉快 + 高唤醒（开心/兴奋）
    "开心", "高兴", "快乐", "兴奋", "太好了", "太棒", "惊喜", "喜欢", "幸福", "爽",
    # 愉快 + 低唤醒（放松/平静/满足）
    "平静", "放松", "安心", "舒服", "惬意", "宁静", "满足", "淡定", "悠闲",
    # 不愉快 + 高唤醒（生气/愤怒/焦虑/恐惧）
    "生气", "愤怒", "气死", "讨厌", "烦", "焦虑", "害怕", "恐惧", "紧张", "担心",
    "崩溃", "暴躁",
    # 不愉快 + 低唤醒（委屈/悲伤/低落/疲惫）
    "委屈", "难过", "伤心", "悲伤", "失落", "低落", "郁闷", "孤单", "孤独",
    "疲惫", "累", "沮丧", "失望", "无奈",
]


def _build_vocab():
    return {kw: i for i, kw in enumerate(KEYWORDS)}


_VOCAB = _build_vocab()


def encode_text(text: str) -> np.ndarray:
    """把中文语句编码为词袋向量（关键词是否出现）。"""
    vec = np.zeros(len(KEYWORDS), dtype=float)
    for kw, idx in _VOCAB.items():
        if kw in text:
            vec[idx] = 1.0
    return vec


